using Assets.Script.Core.GamePlay;
using Assets.Script.Core.GameRoot.GameState;
using System;
using System.IO;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace Assets.Script.Core.GameRoot
{
    public class GameRoot : MonoBehaviour
    {
        private static GameRoot instance;
        public static GameRoot Instance => instance;

        private GameSession gameSession;
        public GameSession Session => gameSession;

        private GameStateMachine gameState;
        public GameStateMachine StateMachine => gameState;

        private ShopManager shopManager;
        private Inventory inventory;
        private DebtManager debtManager;
        private EndingSystem endingSystem;
        private ItemSpawnManager itemSpawnManager;

        private void Awake()
        {
            if (instance != null && instance != this)
            {
                Destroy(gameObject);
                return;
            }

            instance = this;

            DontDestroyOnLoad(gameObject);
            Initialize();
        }

        private void Initialize()
        {
            gameSession = new GameSession();

            gameState = new GameStateMachine(
                new MainMenuState(StartGame, LoadGame));
        }

#if UNITY_EDITOR
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        private static void AutoBootstrapInEditor()
        {
            if (instance == null)
            {
                string activeScene = SceneManager.GetActiveScene().name;
                if (activeScene == "MainMenu")
                {
                    GameObject rootGo = new GameObject("[GameRoot_AutoGenerated]");
                    rootGo.AddComponent<GameRoot>();
                    Debug.Log("<color=cyan>[GameRoot] Tự động khởi tạo GameRoot khi Play trực tiếp từ MainMenu scene.</color>");
                }
            }
        }
#endif

        public void LoadMainMenuScene()
        {
            gameState.ChangeState(
                new MainMenuState(StartGame, LoadGame));
        }

        [ContextMenu("Chạy Hàm Test")]
        public void StartGame()
        {
            ShopOfferData starter =
                ItemManager.GetNormalShopItemData("StarterPotion");

            if (starter == null)
            {
                Debug.LogError("Không tìm thấy offer của StarterPotion.");
                return;
            }

            gameSession.StartNewGame(starter.price);
            InitializeManagers();
            AutoSave();

            gameState.ChangeState(new ShopState(
                shopManager,
                gameState,
                itemSpawnManager,
                inventory,
                gameSession.Data,
                ShowSummary,
                LoadMainMenuScene));
        }

        private void PrepareNextDay()
        {
            gameSession.AdvanceDay();
            shopManager.RestockNormalShop();
            AutoSave();

            gameState.ChangeState(
                new ShopState(
                    shopManager,
                    gameState,
                    itemSpawnManager,
                    inventory,
                    gameSession.Data,
                    ShowSummary,
                    LoadMainMenuScene));
        }

        public void AutoSave()
        {
            if (gameSession.Data == null)
                return;

            SaveSystem.Save(gameSession.Data, 0);
        }

        private void InitializeManagers()
        {
            GameData data = gameSession.Data;
            this.inventory = new Inventory(data.inventoryData);
            this.debtManager = new DebtManager(data);
            this.itemSpawnManager = new ItemSpawnManager(data);
            this.shopManager = new ShopManager(inventory, data, debtManager);
            this.endingSystem = new EndingSystem(data);
        }

        public void LoadGame(int slotId)
        {
            GameData data = SaveSystem.Load(slotId);
            if (data == null)
            {
                Debug.LogWarning($"Không có save ở ô {slotId}");
                return;
            }
            gameSession.SetData(data);
            InitializeManagers();
            gameState.ChangeState(new ShopState(
                shopManager,
                gameState,
                itemSpawnManager,
                inventory,
                gameSession.Data,
                ShowSummary,
                LoadMainMenuScene));
        }

        public void ShowSummary(RunResult runResult)
        {
            if (runResult == null)
            {
                Debug.LogError("[GameRoot] ShowSummary nhận runResult null! Tạo fallback RunResult để bảo đảm flow không gãy.");
                runResult = new RunResult
                {
                    day = gameSession.Data != null ? gameSession.Data.currentDay : 1,
                    survivalTime = 0f,
                    money = 0,
                    failed = true
                };
            }

            gameState.ChangeState(
                new SummaryState(
                    runResult,
                    gameSession.Data,
                    debtManager,
                    endingSystem,
                    gameState,
                    PrepareNextDay,
                    LoadMainMenuScene));
        }

        public void RestartCurrentRun()
        {
            Time.timeScale = 1f;

            if (gameState != null && gameSession != null && gameSession.Data != null)
            {
                gameState.ChangeState(
                    new SurvivalState(
                        gameState,
                        itemSpawnManager,
                        inventory,
                        gameSession.Data,
                        ShowSummary,
                        forceReload: true),
                    force: true);
            }
            else
            {
                if (AsyncLoader.Instance != null)
                {
                    AsyncLoader.Instance.StartLoading("GamePlaySence");
                }
                else
                {
                    UnityEngine.SceneManagement.SceneManager.LoadScene("GamePlaySence");
                }
            }
        }

        public void ReturnToMainMenu()
        {
            Time.timeScale = 1f;
            LoadMainMenuScene();
        }
    }
}
